/**
 * 주어진 날짜(KST 기준)에 올릴 기도제목을 고릅니다.
 * 요일로 주제를 정하고, 몇 번째 주인지로 그 안의 문장을 골라
 * 같은 요일이 돌아와도 문장이 반복되지 않게 합니다.
 */
export function pickPrayerTopic(kstDate: Date): PrayerTopic {
  const day = kstDate.getUTCDay();
  const pool = TOPICS_BY_DAY[day];

  // 1970-01-01 이후 몇 번째 주인지 — 주가 바뀔 때마다 다른 문장이 나옵니다.
  const weekIndex = Math.floor(
    Date.UTC(kstDate.getUTCFullYear(), kstDate.getUTCMonth(), kstDate.getUTCDate()) /
      (7 * 86400000)
  );

  return pool[weekIndex % pool.length];
}
